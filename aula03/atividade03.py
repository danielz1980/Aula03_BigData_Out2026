num1 = float(input("Informe o primeiro número (A): "))
num2 = float(input("Informe o segundo número (B): "))

soma = num1 + num2
subtracao = num1 - num2
multiplicacao = num1 * num2
divisao = num1 / num2

print(f"Soma dos números (A + B): {soma:.2f}")
print(f"Subtração dos números (A - B): {subtracao:.2f}")
print(f"Multiplicação dos números (A * B): {multiplicacao:.2f}")
print(f"Divisão dos números (A / B): {divisao:.2f}")